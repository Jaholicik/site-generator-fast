// A faster drop-in for makefun-site 1.0.0: run(input) returns exactly makefun-site 1.0.0's build of the input, byte
// for byte, on every input. The pipeline is makefun-site's own (sources, front matter, permalinks, Markdown,
// collections, tags, layouts, report), restructured where the reference spends its time: the inline renderer moves in
// indexOf jumps and escapes whole runs at once instead of a character at a time, the reference's own escape-aware
// scanners remain as the fallback wherever a backslash is present, slugify has an ASCII fast path (NFKD is the
// identity there) and a per-build memo, and the line trims and word counts are scans, not regex matches.

const ESCAPES = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };
const ESC_RE = /[&<>"']/;
const ESC_RE2 = /[&<>"']/g;
/** The characters that can open an inline construct: backslash, backtick, star, [. */
const SPECIAL_RE = /[\\`*\[]/g;

/** `text` with & < > " and ' escaped (the reference's table, applied to a whole run at once). */
function escapeHtml(text) {
  return ESC_RE.test(text) ? text.replace(ESC_RE2, (c) => ESCAPES[c]) : text;
}

const SLUG_MAX = 64;

/** The reference slugify, verbatim, for text outside ASCII (NFKD, marks dropped, then the shared tail). */
function slugifySlow(text) {
  const plain = text.normalize('NFKD').replace(/\p{M}/gu, '');
  let out = '';
  let gap = false;
  for (const ch of plain) {
    let keep = null;
    if (ch >= 'A' && ch <= 'Z') keep = ch.toLowerCase();
    else if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) keep = ch;
    if (keep === null) {
      gap = out.length > 0;
      continue;
    }
    if (gap) out += '-';
    gap = false;
    out += keep;
  }
  out = out.slice(0, SLUG_MAX).replace(/-+$/, '');
  return out === '' ? 'untitled' : out;
}

/** The slug of `text`: on pure ASCII, NFKD changes nothing and no combining mark occurs, so the loop is direct. */
function slugifyRaw(text) {
  let ascii = true;
  for (let i = 0; i < text.length; i++) {
    if (text.charCodeAt(i) > 127) {
      ascii = false;
      break;
    }
  }
  if (!ascii) return slugifySlow(text);
  // Runs of [a-z0-9] are copied as one slice; an [A-Z] is one lowercased char; anything else is a gap.
  let out = '';
  let gap = false;
  let runStart = -1;
  for (let i = 0; i < text.length; i++) {
    const code = text.charCodeAt(i);
    if ((code >= 97 && code <= 122) || (code >= 48 && code <= 57)) {
      if (runStart === -1) {
        if (gap) {
          out += '-';
          gap = false;
        }
        runStart = i;
      }
    } else if (code >= 65 && code <= 90) {
      if (runStart !== -1) {
        out += text.slice(runStart, i);
        runStart = -1;
      }
      if (gap) {
        out += '-';
        gap = false;
      }
      out += String.fromCharCode(code + 32);
    } else {
      if (runStart !== -1) {
        out += text.slice(runStart, i);
        runStart = -1;
      }
      gap = out.length > 0;
    }
  }
  if (runStart !== -1) out += text.slice(runStart);
  out = out.slice(0, SLUG_MAX).replace(/-+$/, '');
  return out === '' ? 'untitled' : out;
}

/** `slug` made unique against `taken` (and added to it): the first of slug, slug-2, slug-3 ... not taken. */
function uniqueSlug(slug, taken) {
  let out = slug;
  for (let n = 2; taken.has(out); n++) out = `${slug}-${n}`;
  taken.add(out);
  return out;
}

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

/** A YYYY-MM-DD date in words, from the string alone. */
function longDateRaw(date) {
  const [y, m, d] = date.split('-');
  return `${Number(d)} ${MONTHS[Number(m) - 1]} ${y}`;
}

// ---------------------------------------------------------------- front matter

const KEYS = new Set(['title', 'date', 'tags', 'draft', 'layout', 'slug', 'summary']);
const DATE_RE = /^(\d{4})-(\d{2})-(\d{2})$/;
const NAME_RE = /^[a-z0-9-]+$/;
const SLUG_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const TAG_RE = /^[^"[\]]+$/;

function daysIn(y, m) {
  if (m === 2) return (y % 4 === 0 && y % 100 !== 0) || y % 400 === 0 ? 29 : 28;
  return m === 4 || m === 6 || m === 9 || m === 11 ? 30 : 31;
}

/** A string value: "..." with \" and \\ its only escapes, or bare, the rest of the line (never opening on " or [). */
function stringOf(raw) {
  if (raw.startsWith('"')) {
    if (raw.length < 2 || !raw.endsWith('"')) return { error: 'a quoted string is not closed' };
    let out = '';
    for (let i = 1; i < raw.length - 1; i++) {
      const c = raw[i];
      if (c === '\\') {
        const n = raw[i + 1];
        if ((n !== '"' && n !== '\\') || i + 1 === raw.length - 1) return { error: 'a quoted string holds an escape other than \\" or \\\\' };
        out += n;
        i++;
      } else if (c === '"') return { error: 'a quoted string holds a stray quote' };
      else out += c;
    }
    return { value: out };
  }
  if (raw.startsWith('[')) return { error: 'a bare string opens on [' };
  return { value: raw };
}

/** One key's value, or why it is refused. */
function valueOf(key, raw) {
  switch (key) {
    case 'title':
    case 'summary': {
      const s = stringOf(raw);
      return 'error' in s ? { error: `key "${key}": ${s.error}` } : s;
    }
    case 'date': {
      const m = DATE_RE.exec(raw);
      const y = m ? Number(m[1]) : 0;
      const mo = m ? Number(m[2]) : 0;
      const d = m ? Number(m[3]) : 0;
      if (!m || y < 1970 || y > 2099 || mo < 1 || mo > 12 || d < 1 || d > daysIn(y, mo)) return { error: 'key "date": not a date from 1970-01-01 to 2099-12-31 (YYYY-MM-DD)' };
      return { value: raw };
    }
    case 'tags': {
      if (!raw.startsWith('[') || !raw.endsWith(']')) return { error: 'key "tags": not a list [a, b]' };
      const inner = raw.slice(1, -1);
      if (inner.trim() === '') return { value: [] };
      const tags = inner.split(',').map((t) => t.trim());
      if (tags.some((t) => t === '' || !TAG_RE.test(t))) return { error: 'key "tags": an empty tag, or one holding " [ or ]' };
      return { value: tags };
    }
    case 'draft':
      return raw === 'true' ? { value: true } : raw === 'false' ? { value: false } : { error: 'key "draft": true or false' };
    case 'layout':
      return NAME_RE.test(raw) ? { value: raw } : { error: 'key "layout": not a template name' };
    case 'slug':
      return SLUG_RE.test(raw) && raw.length <= 64 ? { value: raw } : { error: 'key "slug": not a slug' };
    default:
      return { error: `unknown key "${key}"` };
  }
}

const isBlankLine = (line) => {
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (c !== ' ' && c !== '\t') return false;
  }
  return true;
};

/** A source's front matter and body: { data, body }, or { error } with the first reason it is refused. */
function parseFrontMatter(text) {
  const firstNl = text.indexOf('\n');
  if ((firstNl === -1 ? text : text.slice(0, firstNl)) !== '---') return { error: 'no front matter' };
  const lines = [];
  let body = null;
  let pos = firstNl === -1 ? text.length : firstNl + 1;
  while (pos <= text.length) {
    const nl = text.indexOf('\n', pos);
    const line = nl === -1 ? text.slice(pos) : text.slice(pos, nl);
    if (line === '---') {
      body = nl === -1 ? '' : text.slice(nl + 1);
      break;
    }
    lines.push(line);
    if (nl === -1) break;
    pos = nl + 1;
  }
  if (body === null) return { error: 'the front matter is not closed' };
  const data = {};
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (isBlankLine(line) || line.startsWith('#')) continue;
    // /^([a-z_]+):(?: (.*))?$/ by hand: a run of [a-z_], a colon, then end of line or one space and the rest.
    let p = 0;
    while (p < line.length) {
      const code = line.charCodeAt(p);
      if ((code >= 97 && code <= 122) || code === 95) p++;
      else break;
    }
    let key = null;
    let raw0 = '';
    if (p > 0 && line[p] === ':') {
      if (p === line.length - 1) {
        key = line.slice(0, p);
      } else if (line[p + 1] === ' ') {
        key = line.slice(0, p);
        raw0 = line.slice(p + 2);
      }
    }
    if (key === null) return { error: `line ${i + 2} is not "key: value"` };
    const raw = raw0.replace(/[ \t]+$/, '');
    if (!KEYS.has(key)) return { error: `unknown key "${key}"` };
    if (Object.hasOwn(data, key)) return { error: `key "${key}" is given twice` };
    if (raw === '') return { error: `key "${key}" has no value` };
    const v = valueOf(key, raw);
    if ('error' in v) return v;
    data[key] = v.value;
  }
  if (!Object.hasOwn(data, 'title')) return { error: 'no title' };
  return { data, body };
}

// ---------------------------------------------------------------- markdown

const FENCE_OPEN = /^```([A-Za-z0-9_+-]*)[ \t]*$/;
const FENCE_CLOSE = /^```[ \t]*$/;
const HEADING = /^(#{1,6})[ \t]+(.*?)[ \t]*$/;
const HR = /^(?:---|\*\*\*)[ \t]*$/;
const BULLET = /^[-*] (.*)$/;
const ORDERED = /^(\d{1,9})\. (.*)$/;
const CONTINUED = /^ {2,}\S/;

function headingOf(line) {
  const m = HEADING.exec(line);
  return m === null || m[2] === '' ? null : { depth: m[1].length, text: m[2] };
}

const isBlankText = (line) => {
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (c !== ' ' && c !== '\t') return false;
  }
  return true;
};

/** A paragraph line as it is rendered: spaces and tabs at either end dropped (a scan, not a regex). */
function trimLine(line) {
  let a = 0;
  let b = line.length;
  while (a < b && (line[a] === ' ' || line[a] === '\t')) a++;
  while (b > a && (line[b - 1] === ' ' || line[b - 1] === '\t')) b--;
  return a === 0 && b === line.length ? line : line.slice(a, b);
}

/** Whether `line` ends a paragraph: a blank line, a fence, a heading or a thematic break. */
function endsParagraph(line) {
  if (isBlankText(line)) return true;
  const c = line[0];
  if (c === '`') return FENCE_OPEN.test(line);
  if (c === '#') return headingOf(line) !== null;
  if (c === '-' || c === '*') return HR.test(line);
  return false;
}

/** `src`'s block tokens, in order (the reference lexer, with first-character guards before its regexes). */
function lex(src) {
  const lines = src.split('\n');
  const tokens = [];
  let i = 0;
  while (i < lines.length) {
    const line = lines[i];
    if (isBlankText(line)) {
      i++;
      continue;
    }
    const c0 = line[0];
    if (c0 === '`') {
      const fence = FENCE_OPEN.exec(line);
      if (fence !== null) {
        const body = [];
        i++;
        while (i < lines.length && !FENCE_CLOSE.test(lines[i])) body.push(lines[i++]);
        i++;
        tokens.push({ type: 'code', lang: fence[1], lines: body });
        continue;
      }
    }
    if (c0 === '#') {
      const heading = headingOf(line);
      if (heading !== null) {
        tokens.push({ type: 'heading', depth: heading.depth, text: heading.text });
        i++;
        continue;
      }
    }
    if ((c0 === '-' || c0 === '*') && HR.test(line)) {
      tokens.push({ type: 'hr' });
      i++;
      continue;
    }
    if (c0 === '>') {
      const body = [];
      while (i < lines.length && lines[i][0] === '>') {
        const l = lines[i++];
        body.push(l.startsWith('> ') ? l.slice(2) : l.slice(1));
      }
      tokens.push({ type: 'blockquote', lines: body.map(trimLine).filter((l) => l !== '') });
      continue;
    }
    let bullet = null;
    let ordered = null;
    if ((c0 === '-' || c0 === '*') && line[1] === ' ') bullet = BULLET.exec(line);
    else if (c0 >= '0' && c0 <= '9') ordered = ORDERED.exec(line);
    if (bullet !== null || ordered !== null) {
      const isOrdered = ordered !== null;
      const items = [];
      while (i < lines.length) {
        const l = lines[i];
        let m = null;
        if (isOrdered) {
          const d = l[0];
          if (d >= '0' && d <= '9') m = ORDERED.exec(l);
        } else {
          const d = l[0];
          if ((d === '-' || d === '*') && l[1] === ' ') m = BULLET.exec(l);
        }
        if (m !== null) {
          items.push([trimLine(isOrdered ? m[2] : m[1])]);
          i++;
        } else if (CONTINUED.test(l)) {
          items[items.length - 1].push(trimLine(l));
          i++;
        } else break;
      }
      tokens.push({ type: 'list', ordered: isOrdered, start: isOrdered ? Number(ordered[1]) : 1, items: items.map((parts) => parts.join('\n')) });
      continue;
    }
    const body = [trimLine(line)];
    i++;
    while (i < lines.length && !endsParagraph(lines[i])) body.push(trimLine(lines[i++]));
    tokens.push({ type: 'paragraph', text: body.join('\n') });
  }
  return tokens;
}

/** The characters a backslash escapes. */
const ESCAPABLE = new Set(['\\', '`', '*', '_', '[', ']', '(', ')', '#', '+', '-', '.', '!', '>']);

/** The first index in [from, hi) where `s` holds `what` outside a backslash escape, or -1 (the reference scan). */
function findUnescapedScan(s, what, from, hi) {
  for (let j = from; j + what.length <= hi; j++) {
    if (s[j] === '\\' && j + 1 < hi && ESCAPABLE.has(s[j + 1])) {
      j++;
      continue;
    }
    if (s.startsWith(what, j)) return j;
  }
  return -1;
}

/** The first single * in [from, hi) (one whose run is not **), outside an escape, or -1 (the reference scan). */
function findSingleStarScan(s, from, hi) {
  for (let j = from; j < hi; j++) {
    const c = s[j];
    if (c === '\\' && j + 1 < hi && ESCAPABLE.has(s[j + 1])) {
      j++;
      continue;
    }
    if (c !== '*') continue;
    if (j + 1 < hi && s[j + 1] === '*') {
      j++;
      continue;
    }
    return j;
  }
  return -1;
}

/** findUnescaped when the range holds no backslash: a plain indexOf, bounded by `end`. */
function findUnescapedFast(str, what, from, end) {
  const j = str.indexOf(what, from);
  return j !== -1 && j + what.length <= end ? j : -1;
}

/** findSingleStar when the range holds no backslash: indexOf jumps over ** pairs. */
function findSingleStarFast(str, from, end) {
  let j = str.indexOf('*', from);
  while (j !== -1 && j < end) {
    if (j + 1 >= end || str[j + 1] !== '*') return j;
    j = str.indexOf('*', j + 2);
  }
  return -1;
}

/** The range s[lo, hi) rendered inline; `env.link(target)` is a link's href. Ranges, not slices: no copies. */
function inlineRange(s, lo, hi, env) {
  // Whether a backslash occurs in the range decides the finders: indexOf jumps, or the escape-aware scans.
  const bsAt = s.indexOf('\\', lo);
  const hasBs = bsAt !== -1 && bsAt < hi;
  const findUnescaped = hasBs ? findUnescapedScan : findUnescapedFast;
  const findSingleStar = hasBs ? findSingleStarScan : findSingleStarFast;
  let out = '';
  let i = lo;
  while (i < hi) {
    const c = s.charCodeAt(i);
    if (c === 92) {
      if (i + 1 < hi && ESCAPABLE.has(s[i + 1])) {
        const nx = s[i + 1];
        out += nx === '>' ? '&gt;' : nx;
        i += 2;
      } else {
        out += '\\';
        i++;
      }
      continue;
    }
    if (c === 96) {
      const j = s.indexOf('`', i + 1);
      if (j > i + 1 && j < hi) {
        out += `<code>${escapeHtml(s.slice(i + 1, j))}</code>`;
        i = j + 1;
      } else {
        out += '`';
        i++;
      }
      continue;
    }
    if (c === 42) {
      if (i + 1 < hi && s[i + 1] === '*') {
        const j = findUnescaped(s, '**', i + 2, hi);
        if (j > i + 2) {
          out += `<strong>${inlineRange(s, i + 2, j, env)}</strong>`;
          i = j + 2;
        } else {
          out += '**';
          i += 2;
        }
        continue;
      }
      const j = findSingleStar(s, i + 1, hi);
      if (j > i + 1) {
        out += `<em>${inlineRange(s, i + 1, j, env)}</em>`;
        i = j + 1;
      } else {
        out += '*';
        i++;
      }
      continue;
    }
    if (c === 91) {
      const k = findUnescaped(s, ']', i + 1, hi);
      const m = k !== -1 && k + 1 < hi && s[k + 1] === '(' ? s.indexOf(')', k + 2) : -1;
      const target = m === -1 || m >= hi ? '' : s.slice(k + 2, m);
      if (target !== '' && !/\s/.test(target)) {
        out += `<a href="${escapeHtml(env.link(target))}">${inlineRange(s, i + 1, k, env)}</a>`;
        i = m + 1;
        continue;
      }
      out += '[';
      i++;
      continue;
    }
    // A plain run: everything up to the next character that can open a construct, escaped in one pass.
    SPECIAL_RE.lastIndex = i + 1;
    const sm = SPECIAL_RE.exec(s);
    const j = sm === null || sm.index >= hi ? hi : sm.index;
    out += escapeHtml(s.slice(i, j));
    i = j;
  }
  return out;
}

/** `s` rendered inline; `env.link(target)` is a link's href. */
function inline(s, env) {
  return inlineRange(s, 0, s.length, env);
}

/**
 * `src` rendered: its HTML, its table of contents and its excerpt. `slugify` is the build's memoised slug.
 */
function renderMarkdown(src, env, slugify) {
  const ids = new Set();
  const blocks = [];
  const toc = [];
  let excerpt = null;
  for (const t of lex(src)) {
    switch (t.type) {
      case 'heading': {
        const id = uniqueSlug(slugify(t.text), ids);
        const html = inline(t.text, env);
        blocks.push(`<h${t.depth} id="${id}">${html}</h${t.depth}>`);
        if (t.depth === 2 || t.depth === 3) toc.push({ level: t.depth, id, html });
        break;
      }
      case 'code': {
        const cls = t.lang === '' ? '' : ` class="language-${escapeHtml(t.lang)}"`;
        blocks.push(`<pre><code${cls}>${t.lines.map((l) => `${escapeHtml(l)}\n`).join('')}</code></pre>`);
        break;
      }
      case 'hr':
        blocks.push('<hr>');
        break;
      case 'blockquote':
        blocks.push(t.lines.length === 0 ? '<blockquote>\n</blockquote>' : `<blockquote>\n<p>${inline(t.lines.join('\n'), env)}</p>\n</blockquote>`);
        break;
      case 'list': {
        const tag = t.ordered ? 'ol' : 'ul';
        const open = t.ordered && t.start !== 1 ? `<ol start="${t.start}">` : `<${tag}>`;
        blocks.push(`${open}\n${t.items.map((item) => `<li>${inline(item, env)}</li>\n`).join('')}</${tag}>`);
        break;
      }
      case 'paragraph': {
        const html = inline(t.text, env);
        if (excerpt === null) excerpt = html;
        blocks.push(`<p>${html}</p>`);
        break;
      }
    }
  }
  return { html: blocks.map((b) => `${b}\n`).join(''), toc, excerpt: excerpt ?? '' };
}

